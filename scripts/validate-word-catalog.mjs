import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = new URL("../", import.meta.url);
const catalogUrl = new URL("packages/game-core/data/word-catalog.csv", root);
const generatedUrl = new URL("packages/game-core/src/catalog.generated.ts", root);
const header = "word,allowed_guess,daily_answer,free_play_answer,rarity,active";
const rarities = new Set(["common", "rare"]);

const source = (await readFile(catalogUrl, "utf8")).replaceAll("\r\n", "\n").trim();
const [actualHeader, ...lines] = source.split("\n");
const errors = [];
const seen = new Set();

if (actualHeader !== header) errors.push(`Expected CSV header: ${header}`);

const words = lines.map((line, index) => {
  const rowNumber = index + 2;
  const [word, allowedGuess, dailyAnswer, freePlayAnswer, rarity, active, ...extra] =
    line.split(",");

  if (extra.length > 0) errors.push(`Row ${rowNumber} has too many columns.`);
  if (!/^[a-z]{5}$/.test(word ?? "")) {
    errors.push(`Row ${rowNumber} must contain one lowercase five-letter word.`);
  }
  if (seen.has(word)) errors.push(`Row ${rowNumber} duplicates ${word}.`);
  seen.add(word);

  for (const [name, value] of [
    ["allowed_guess", allowedGuess],
    ["daily_answer", dailyAnswer],
    ["free_play_answer", freePlayAnswer],
    ["active", active],
  ]) {
    if (value !== "true" && value !== "false") {
      errors.push(`Row ${rowNumber} has invalid ${name}: ${value ?? "missing"}.`);
    }
  }

  if (!rarities.has(rarity)) errors.push(`Row ${rowNumber} has invalid rarity: ${rarity}.`);
  if ((dailyAnswer === "true" || freePlayAnswer === "true") && allowedGuess !== "true") {
    errors.push(`Row ${rowNumber} uses ${word} as an answer without allowing it as a guess.`);
  }

  return {
    word,
    allowedGuess: allowedGuess === "true",
    dailyAnswer: dailyAnswer === "true",
    freePlayAnswer: freePlayAnswer === "true",
    rarity,
    active: active === "true",
  };
});

const common = words.filter((entry) => entry.active && entry.rarity === "common");
const rare = words.filter((entry) => entry.active && entry.rarity === "rare");
if (common.length !== 2309) errors.push(`Expected 2,309 Common words; found ${common.length}.`);
if (rare.length !== 10657) errors.push(`Expected 10,657 Rare words; found ${rare.length}.`);
if (words.length !== 12966) errors.push(`Expected 12,966 total words; found ${words.length}.`);

for (const entry of common) {
  if (!entry.allowedGuess || !entry.dailyAnswer || !entry.freePlayAnswer) {
    errors.push(`${entry.word} must be enabled for guesses, Daily, and Free Play as Common.`);
  }
}
for (const entry of rare) {
  if (!entry.allowedGuess || entry.dailyAnswer || !entry.freePlayAnswer) {
    errors.push(`${entry.word} must be guess/Free-Play eligible and Daily-ineligible as Rare.`);
  }
}

if (errors.length > 0) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const generatedSource =
  `// Generated by scripts/validate-word-catalog.mjs. Do not edit directly.\n` +
  `import type { WordRarity } from "./index";\n\n` +
  `export type CatalogWord = {\n` +
  `  word: string;\n` +
  `  allowedGuess: boolean;\n` +
  `  dailyAnswer: boolean;\n` +
  `  freePlayAnswer: boolean;\n` +
  `  rarity: WordRarity;\n` +
  `  active: boolean;\n` +
  `};\n\n` +
  `export const WORD_CATALOG = ${JSON.stringify(words, null, 2)} as const satisfies readonly CatalogWord[];\n\n` +
  `export const ALLOWED_GUESSES = new Set(\n` +
  `  WORD_CATALOG.filter((entry) => entry.active && entry.allowedGuess).map((entry) => entry.word),\n` +
  `);\n\n` +
  `export const FREE_PLAY_WORDS = WORD_CATALOG.filter(\n` +
  `  (entry) => entry.active && entry.freePlayAnswer,\n` +
  `);\n`;
const generated = await format(generatedSource, { parser: "typescript", printWidth: 100 });

if (process.argv.includes("--write")) {
  await writeFile(generatedUrl, generated);
  console.log(`Generated ${fileURLToPath(generatedUrl)} from ${words.length} catalog rows.`);
} else {
  let existing = "";
  try {
    existing = await readFile(generatedUrl, "utf8");
  } catch {
    // The comparison below reports the missing generated file.
  }
  if (existing.replaceAll("\r\n", "\n") !== generated) {
    console.error("The generated word catalog is stale. Run: pnpm catalog:write");
    process.exit(1);
  }
  console.log(`Word catalog validated (${words.length} rows).`);
}
