import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const catalogUrl = new URL("packages/game-core/data/word-catalog.csv", root);
const migrationUrl = new URL("supabase/migrations/20260829041000_m4_daily_word_catalog.sql", root);
const expectedHeader = "word,allowed_guess,daily_answer,free_play_answer,rarity,active";

const source = (await readFile(catalogUrl, "utf8")).replaceAll("\r\n", "\n").trim();
const [header, ...lines] = source.split("\n");
if (header !== expectedHeader) throw new Error(`Expected CSV header: ${expectedHeader}`);

const entries = lines.map((line, index) => {
  const [word, allowedGuess, dailyAnswer, , , active, ...extra] = line.split(",");
  if (
    extra.length > 0 ||
    !/^[a-z]{5}$/.test(word) ||
    allowedGuess !== "true" ||
    !["true", "false"].includes(dailyAnswer) ||
    active !== "true"
  ) {
    throw new Error(`Catalog row ${index + 2} cannot be imported safely.`);
  }
  return { word, answerEligible: dailyAnswer === "true" };
});

const answerCount = entries.filter((entry) => entry.answerEligible).length;
if (entries.length !== 12966 || answerCount !== 2309) {
  throw new Error(
    `Expected 12,966 accepted words and 2,309 Daily answers; found ${entries.length} and ${answerCount}.`,
  );
}

const values = entries
  .map((entry) => `  ('${entry.word}', ${entry.answerEligible}, true)`)
  .join(",\n");
const migration = `-- Generated by scripts/generate-daily-word-migration.mjs.
-- Exact archived Wordle catalog: 12,966 accepted guesses and 2,309 Daily answers.

insert into private.daily_words (word, answer_eligible, active)
values
${values}
on conflict (word) do update
set answer_eligible = excluded.answer_eligible,
    active = excluded.active;

do $$
begin
  assert (select count(*) from private.daily_words where active) = 12966,
    'Daily accepted-word import count is incorrect';
  assert (select count(*) from private.daily_words where active and answer_eligible) = 2309,
    'Daily answer import count is incorrect';
end
$$;
`;

if (process.argv.includes("--write")) {
  await writeFile(migrationUrl, migration);
  console.log(
    `Generated ${fileURLToPath(migrationUrl)} with ${entries.length} accepted words and ${answerCount} Daily answers.`,
  );
} else {
  let existing = "";
  try {
    existing = await readFile(migrationUrl, "utf8");
  } catch {
    // The comparison below reports the missing generated migration.
  }

  if (existing.replaceAll("\r\n", "\n") !== migration) {
    console.error("The generated Daily database catalog is stale. Run: pnpm daily-catalog:write");
    process.exit(1);
  }

  console.log(
    `Daily database catalog validated (${entries.length} accepted words; ${answerCount} Daily answers).`,
  );
}
